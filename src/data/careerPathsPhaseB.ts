function buildBatchCareer(
  label: string,
  category: CareerPath['category'],
  index: number,
): CareerPath {
  const slug = label.toLowerCase().replace(/[^a-z0-9]+/g, '_');
  return {
    id: `batch_${category}_${slug}`,
    label,
    category,
    isEntryLevel: index % 2 === 0,
    seniorityLevel: ((index % 4) + 1) as 1 | 2 | 3 | 4 | 5,
    description: `Build a career as a ${label.toLowerCase()}.`,
    company: 'Various Employers',
    baseSalary: 38000 + index * 1500,
    maxSalary: 75000 + index * 3500,
    stressLevel: 4 + (index % 4),
    workLifeBalance: 4 + (index % 5),
    requirements: {
      minAge: 18 + (index % 8),
      minEducationStage: index % 3 === 0 ? 'undergraduate' : 'high_school',
      minIntelligence: 45 + (index % 25),
    },
    progressionPaths: [],
    skillTree: DEFAULT_SKILL_TREE(label.split(' ')[0] ?? 'Core'),
  };
}

